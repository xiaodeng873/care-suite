  p."院友id",
  e.d,
  '00:00:00'::time,
  '體重控制',
  e.w,
  '體重匯入'
FROM expanded e
JOIN "院友主表" p ON p."中文姓名" = e.name
WHERE NOT EXISTS (
  SELECT 1
  FROM "健康記錄主表" h
  WHERE h."院友id" = p."院友id"
    AND h."記錄日期" = e.d
    AND h."記錄類型" = '體重控制'
);

