/*
  # 多租戶改造（第一步）：新增 facilities 院舍表及各表 facility_id 欄位

  目的：為多租戶改造建立 schema 基礎。

  1. 新建 facilities 院舍表，並以 id = 1 作為現有資料的預設院舍。
  2. user_profiles（員工）及院舍級資源表加 facility_id 並回填 1。
  3. 院友主表加 facility_id（tenant 邊界根），所有院友級資料表加冗余
     facility_id，並以 BEFORE INSERT trigger 由院友主表自動填入，
     現有前端 db 函式無需修改。
  4. 共用參考資料表（藥物資料庫、問題庫、範本等）完全不加欄位。
  5. 本 migration 不處理 RLS（developer 跨院舍等於 P2 處理）。

  全部使用 IF NOT EXISTS / IF EXISTS 防重跑；不 DROP 任何現有物件、
  不修改任何現有欄位。
*/

