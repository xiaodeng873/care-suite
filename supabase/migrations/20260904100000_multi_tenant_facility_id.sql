  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE facilities IS '院舍（租戶）主表；多租戶改造的 tenant 邊界';
COMMENT ON COLUMN facilities.id IS '院舍編號';
COMMENT ON COLUMN facilities.name IS '院舍名稱';
COMMENT ON COLUMN facilities.is_active IS '是否啟用';
COMMENT ON COLUMN facilities.created_at IS '建立時間';

