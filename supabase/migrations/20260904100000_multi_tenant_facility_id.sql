RETURNS trigger AS $func$
DECLARE
  v_patient_id integer;
BEGIN
  IF NEW.facility_id IS NOT NULL THEN
    RETURN NEW;
  END IF;
  EXECUTE format('SELECT %s', TG_ARGV[0]) INTO v_patient_id USING NEW;
  IF v_patient_id IS NULL THEN
    RETURN NEW;
  END IF;
  SELECT facility_id INTO NEW.facility_id
  FROM "院友主表"
  WHERE "院友id" = v_patient_id;
  RETURN NEW;
END;
$func$ LANGUAGE plpgsql;

COMMENT ON FUNCTION set_facility_id_from_patient() IS '院友級資料表 INSERT 時由院友主表自動填入 facility_id；TG_ARGV[0] 為回傳院友 id 的 SQL 表達式（$1 = NEW）';

